# -*- coding: utf-8 -*-
"""界面主题 —— 颜色与视觉常量。

**本模块刻意不 import Qt**（与 ``c_core`` 其余部分同一条约定）：
颜色是纯数据，可以先脱离图形环境单测；Qt 层（``ui/``）用
:func:`hex_to_rgb` 把它们转成 ``QColor``。

--------------------------------------------------------------------------
为什么颜色值得一个独立模块
--------------------------------------------------------------------------
美化之前，颜色散在两个绘制文件里（左栏只有黑白，右栏两档灰）。
美化引入「状态色」之后，同一个颜色要同时出现在**两栏**上 ——
左栏脸后面的氛围光、右栏状态胶囊的底色，必须是同一个色值，
否则两栏看起来像两个产品。散落的十六进制字面量做不到这一点。

--------------------------------------------------------------------------
状态色的取值原则（适老化）
--------------------------------------------------------------------------
1. **四态色相彼此远离**（绿 / 蓝 / 琥珀 / 紫）：色弱老人靠色相而不是
   亮度分辨，绿-红、蓝-紫这类邻近对要避开 —— 绿-紫、蓝-琥珀都隔得很开。
2. **统一取柔和的中间调**（≈400 档）：太饱和（红绿灯那种）在纯黑底上
   会刺眼，太浅又和正文白字混在一起。
3. **normal 用绿而不是蓝**：绿色在中文语境里就是「正常」，不需要学习。
"""

from __future__ import annotations

from typing import Dict, Tuple

from c_core.expressions import normalize_state

# --------------------------------------------------------------------------
# 状态色（api_doc §4.2 的四态，键与 c_core.expressions 对齐）
# --------------------------------------------------------------------------

#: 状态 → 主题色。**新增状态时**这里必须同步加，否则回落到 normal 的绿色。
STATE_ACCENTS: Dict[str, str] = {
    "normal": "#34d399",   # 翠绿 —— 一切正常
    "sad":    "#60a5fa",   # 蓝    —— 情绪低落
    "tired":  "#fbbf24",   # 琥珀  —— 疲惫
    "absent": "#a78bfa",   # 紫罗兰 —— 走神 / 无人
}

#: 未知状态回落（与 normalize_state 的回落一致，双保险）。
DEFAULT_ACCENT = STATE_ACCENTS["normal"]


def state_accent(state: object) -> str:
    """状态 → 主题色（十六进制）。任何输入都不抛（与 normalize_state 同脾气）。"""
    return STATE_ACCENTS.get(normalize_state(state), DEFAULT_ACCENT)


def hex_to_rgb(value: str) -> Tuple[int, int, int]:
    """``"#34d399"`` → ``(0x34, 0xd3, 0x99)``。Qt 层拿它构造 ``QColor``。"""
    v = value.strip().lstrip("#")
    if len(v) != 6:
        raise ValueError(f"主题色必须是 #RRGGBB，收到 {value!r}")
    return int(v[0:2], 16), int(v[2:4], 16), int(v[4:6], 16)


# --------------------------------------------------------------------------
# 中性色（右栏文字 / 描边 / 轨道）
# --------------------------------------------------------------------------

#: 正文（数值、状态胶囊文字）—— 接近纯白但柔和一点
TEXT_PRIMARY = "#f4f4f5"
#: 次要正文（细节行）
TEXT_SECONDARY = "#c8c8cd"
#: 弱化文字（区块标签、免责声明）—— 与原 GREY(140) 保持同一观感档
TEXT_MUTED = "#8c8c94"
#: 最弱文字（通道行）—— 与原 DIM(100) 同档
TEXT_FAINT = "#64646a"

#: 专注度进度条的轨道与描边（有分数时上面再画实心段）
TRACK = "#232328"
TRACK_BORDER = "#333338"

#: 画面框外描边（很低调的白，让框在黑底上「存在」但不抢戏）
PANEL_BORDER = "#2e2e33"

# --------------------------------------------------------------------------
# 语义色（与状态色无关的固定含义）
# --------------------------------------------------------------------------

#: 专注度进度条 / 区块标签的主题色 —— **刻意与状态色无关**：
#: 专注度是「另一栏数字」（README §4.3），左栏那张脸不跟着它变；
#: 若给它用状态色，两栏会被误读成同一条状态的两种表达。
#: 取青绿色（teal），与四态色相都隔得开。
ACCENT_VAI = "#2dd4bf"

#: 通道 / 画面「通」与「断」。绿 = 在线，红 = 断开。
LIVE_OK = "#34d399"
LIVE_BAD = "#f87171"

#: 右栏背景渐变：顶部略提亮、底部回到纯黑，给纯黑底一层纵深。
#: 数值压得很低 —— 它是「黑里的层次」，不是「灰底」。
BG_TOP = "#0a0a0c"
BG_BOTTOM = "#000000"
